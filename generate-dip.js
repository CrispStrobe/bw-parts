function generate(chip) {
  const svgContent = generateSvg(chip);
  const jsonContent = generateJson(chip);

  const svgPath = path.join(PARTS_DIR, `${chip.kind}.svg`);
  const jsonPath = path.join(PARTS_DIR, `${chip.kind}.json`);

  fs.writeFileSync(svgPath, svgContent);
  fs.writeFileSync(jsonPath, JSON.stringify(jsonContent, null, 2) + '\n');
  console.log(`  ${chip.kind} (${chip.pinCount}-pin): ${svgPath}`);
}

const target = process.argv[2];
if (target) {
  const chip = PIN_MAPS.find(c => c.kind === target);
  if (!chip) {
    console.error(`Unknown chip: ${target}. Available: ${PIN_MAPS.map(c => c.kind).join(', ')}`);
    process.exit(1);
  }
  generate(chip);
} else {
  console.log(`Generating ${PIN_MAPS.length} DIP ICs...`);
  for (const chip of PIN_MAPS) {
    generate(chip);
  }
  console.log(`Done. ${PIN_MAPS.length} chips generated.`);
}
