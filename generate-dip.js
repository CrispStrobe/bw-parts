#!/usr/bin/env node
/**
 * generate-dip.js — Parametric DIP IC SVG + JSON sidecar generator.
 *
 * Given a pin-map table (chip kind, pin count, pin names, label),
 * generates bench-style DIP package SVGs and matching JSON sidecars
 * in parts/<kind>.svg and parts/<kind>.json.
 *
 * DIP geometry:
 *   Pin 1 is top-left, numbering goes DOWN the left side then
 *   UP the right side (standard DIP convention).
 *   VCC is typically the top-right pin, GND the bottom-left.
 *
 * Usage: node generate-dip.js          (generates all chips in PIN_MAPS)
 *        node generate-dip.js 74hc00   (generates one chip)
 */

const fs = require('fs');
const path = require('path');

const PARTS_DIR = path.join(__dirname, 'parts');

// ── DIP geometry constants ──────────────────────────────────────────
const PIN_SPACING = 5;       // vertical spacing between pins
const PIN_LENGTH  = 10;      // lead wire length from body edge
const BODY_X      = 10;      // left edge of IC body
const BODY_RX     = 2;       // corner radius
const PAD_R       = 1.5;     // terminal pad radius
const PIN_STROKE  = 1.5;
const NOTCH_R     = 3;       // notch semicircle radius
const DOT_R       = 1.5;    // pin-1 dot radius

function dipGeometry(pinCount) {
  const half = pinCount / 2;
  const bodyH = (half - 1) * PIN_SPACING + 12;  // padding top/bottom
  const bodyW = pinCount > 20 ? 60 : 50;        // wider body for DIP-40+
  const svgW  = bodyW + 2 * BODY_X;
  const svgH  = bodyH + 4;  // small margin
  const bodyY = 2;
  return { half, bodyH, bodyW, svgW, svgH, bodyY };
}

function pinY(index, half, bodyY) {
  // index 0 = pin 1 (top-left), index half-1 = bottom-left
  const topPad = 6;
  return bodyY + topPad + index * PIN_SPACING;
}

// ── SVG generation ──────────────────────────────────────────────────
function generateSvg(chip) {
  const { kind, pinCount, pins, label, sublabel } = chip;
  const { half, bodyH, bodyW, svgW, svgH, bodyY } = dipGeometry(pinCount);
  const bodyRight = BODY_X + bodyW;

  let svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${svgW} ${svgH}" width="${svgW}" height="${svgH}">\n`;
  svg += `  <!-- ${label} — ${pinCount}-pin DIP, generated by generate-dip.js -->\n`;

  // Body
  svg += `  <rect x="${BODY_X}" y="${bodyY}" width="${bodyW}" height="${bodyH}" rx="${BODY_RX}" fill="#303030" stroke="#1a1a1a" stroke-width="1"/>\n`;

  // Notch at top center
  const notchCx = BODY_X + bodyW / 2;
  svg += `  <path d="M${notchCx - NOTCH_R} ${bodyY} A${NOTCH_R} ${NOTCH_R} 0 0 1 ${notchCx + NOTCH_R} ${bodyY}" fill="#303030" stroke="#555" stroke-width="0.8"/>\n`;

  // Pin 1 dot
  const dotX = BODY_X + 5;
  const dotY = bodyY + 5;
  svg += `  <circle cx="${dotX}" cy="${dotY}" r="${DOT_R}" fill="#b0b0b0"/>\n`;

  // Label
  const labelY = bodyY + bodyH / 2 - 1;
  svg += `  <text x="${BODY_X + bodyW / 2}" y="${labelY}" text-anchor="middle" font-family="monospace" font-size="5.5" fill="#c0c0c0">${label}</text>\n`;
  if (sublabel) {
    svg += `  <text x="${BODY_X + bodyW / 2}" y="${labelY + 8}" text-anchor="middle" font-family="monospace" font-size="3.5" fill="#888">${sublabel}</text>\n`;
  }

  // Pins — left side (pin 1 to pin half)
  for (let i = 0; i < half; i++) {
    const py = pinY(i, half, bodyY);
    const pinNum = i + 1;
    const pinName = pins[i] || `p${pinNum}`;
    // Lead wire
    svg += `  <line x1="0" y1="${py}" x2="${BODY_X}" y2="${py}" stroke="#aaa" stroke-width="${PIN_STROKE}" stroke-linecap="round"/>\n`;
    // Pad
    svg += `  <circle cx="0" cy="${py}" r="${PAD_R}" fill="#c0c0c0"/>\n`;
    // Pin label (inside body, near left edge)
    const labelFontSize = pinName.length > 4 ? 2.5 : 3;
    svg += `  <text x="${BODY_X + 3}" y="${py + 1}" font-family="monospace" font-size="${labelFontSize}" fill="#888">${pinName}</text>\n`;
  }

  // Pins — right side (pin pinCount down to pin half+1)
  for (let i = 0; i < half; i++) {
    const py = pinY(half - 1 - i, half, bodyY);  // mirrored: top-right is highest pin number
    const pinNum = half + 1 + i;
    const pinName = pins[pinNum - 1] || `p${pinNum}`;
    // Lead wire
    svg += `  <line x1="${bodyRight}" y1="${py}" x2="${svgW}" y2="${py}" stroke="#aaa" stroke-width="${PIN_STROKE}" stroke-linecap="round"/>\n`;
    // Pad
    svg += `  <circle cx="${svgW}" cy="${py}" r="${PAD_R}" fill="#c0c0c0"/>\n`;
    // Pin label (inside body, near right edge)
    const labelFontSize = pinName.length > 4 ? 2.5 : 3;
    svg += `  <text x="${bodyRight - 3}" y="${py + 1}" text-anchor="end" font-family="monospace" font-size="${labelFontSize}" fill="#888">${pinName}</text>\n`;
  }

  svg += `</svg>\n`;
  return svg;
}

// ── JSON sidecar generation ─────────────────────────────────────────
function generateJson(chip) {
  const { kind, pinCount, pins } = chip;
  const { half, svgW, svgH, bodyY } = dipGeometry(pinCount);

  const terminals = [];
  // Left side pins
  for (let i = 0; i < half; i++) {
    const py = pinY(i, half, bodyY);
    const pinName = pins[i] || `p${i + 1}`;
    terminals.push({ name: pinName, x: 0, y: py });
  }
  // Right side pins (bottom-right first = pin half+1, top-right last = pin pinCount)
  for (let i = 0; i < half; i++) {
    const py = pinY(half - 1 - i, half, bodyY);
    const pinNum = half + 1 + i;
    const pinName = pins[pinNum - 1] || `p${pinNum}`;
    terminals.push({ name: pinName, x: svgW, y: py });
  }

  return {
    kind,
    w: svgW,
    h: svgH,
    terminals,
    variants: null,
    ...(chip._note ? { _note: chip._note } : {}),
  };
}

