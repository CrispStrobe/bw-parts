#!/usr/bin/env node
/**
 * generate-display-art.js — SVG for a multi-digit seven-segment sidecar.
 *
 * Same division of labour as generate-dip-art.js: the JSON is the authority
 * and this writes only the missing half, so a pad cannot drift from the
 * terminal coordinate the sidecar publishes. seven_seg_4 is why that matters
 * — it was derived from seven_seg_3 and kept the 3-digit picture at 50 wide
 * while its own JSON said 67, so the art and the sidecar disagreed about
 * where every pin was and the validator only caught the one that had left
 * the canvas entirely.
 *
 * Top pins are y == 0, bottom pins are y == h; anything else is reported
 * rather than guessed.
 *
 * Usage: node generate-display-art.js <kind> <digits> [label] [sublabel]
 */

const fs = require('fs');
const path = require('path');

const PARTS_DIR = path.join(__dirname, 'parts');

function art(kind, sc, digits, label, sub) {
  const { w, h } = sc;
  const PIN_ROW = 5;              // lead length at each edge
  const bodyH = h - PIN_ROW;      // body stops short of the bottom pin row
  const out = [];
  const unplaceable = [];

  out.push(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}">`);
  out.push(`  <!-- ${label} — generated by generate-display-art.js from ${kind}.json -->`);
  out.push(`  <rect x="1" y="1" width="${w - 2}" height="${bodyH - 1}" rx="2" fill="#1a1a2e" stroke="#16213e" stroke-width="1"/>`);

  // Digit windows, evenly spaced across the body with a margin either side.
  const margin = 3;
  const span = w - 2 * margin;
  const cell = span / digits;
  const winW = +(cell * 0.86).toFixed(2);
  const winH = Math.min(20, bodyH - 20);
  out.push(`  <!-- ${digits} digit windows -->`);
  out.push('  <g fill="#0a0a15" stroke="#333" stroke-width="0.5">');
  for (let i = 0; i < digits; i++) {
    const x = +(margin + i * cell + (cell - winW) / 2).toFixed(2);
    out.push(`    <rect x="${x}" y="4" width="${winW}" height="${winH}" rx="1"/>`);
  }
  out.push('  </g>');

  out.push('  <!-- Dim segment placeholders -->');
  out.push('  <g fill="#1a3a1a" opacity="0.3">');
  for (let i = 0; i < digits; i++) {
    const x = +(margin + i * cell + (cell - winW) / 2 + 2).toFixed(2);
    const bw = +(winW - 4).toFixed(2);
    for (const y of [6, 6 + (winH - 8) / 2, winH - 2]) {
      out.push(`    <rect x="${x}" y="${+y.toFixed(2)}" width="${bw}" height="1.5" rx="0.5"/>`);
    }
  }
  out.push('  </g>');

  const midX = +(w / 2).toFixed(2);
  out.push(`  <text x="${midX}" y="${bodyH - 9}" text-anchor="middle" font-family="monospace" font-size="3" fill="#666">${label}</text>`);
  if (sub) {
    out.push(`  <text x="${midX}" y="${bodyH - 3}" text-anchor="middle" font-family="monospace" font-size="2.5" fill="#555">${sub}</text>`);
  }

  const top = sc.terminals.filter((t) => t.y === 0);
  const bottom = sc.terminals.filter((t) => t.y === h);
  for (const t of sc.terminals) {
    if (t.y !== 0 && t.y !== h) unplaceable.push(`${t.name} at (${t.x},${t.y})`);
  }

  if (bottom.length) {
    out.push('  <!-- Bottom pins -->');
    out.push('  <g stroke="#aaa" stroke-width="1" stroke-linecap="round">');
    for (const t of bottom) out.push(`    <line x1="${t.x}" y1="${bodyH}" x2="${t.x}" y2="${h}"/>`);
    out.push('  </g>');
    out.push('  <g fill="#c0c0c0">');
    for (const t of bottom) out.push(`    <circle cx="${t.x}" cy="${h}" r="1"/>`);
    out.push('  </g>');
  }
  if (top.length) {
    out.push('  <!-- Top pins -->');
    out.push('  <g stroke="#aaa" stroke-width="1" stroke-linecap="round">');
    for (const t of top) out.push(`    <line x1="${t.x}" y1="0" x2="${t.x}" y2="1"/>`);
    out.push('  </g>');
    out.push('  <g fill="#c0c0c0">');
    for (const t of top) out.push(`    <circle cx="${t.x}" cy="0" r="1"/>`);
    out.push('  </g>');
  }

  out.push('</svg>');
  return { svg: out.join('\n') + '\n', unplaceable };
}

const [kind, digitsRaw, label, sub] = process.argv.slice(2);
if (!kind || !digitsRaw) {
  console.error('usage: node generate-display-art.js <kind> <digits> [label] [sublabel]');
  process.exit(2);
}
const jsonPath = path.join(PARTS_DIR, `${kind}.json`);
if (!fs.existsSync(jsonPath)) {
  console.error(`no ${kind}.json`);
  process.exit(1);
}
const sc = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
const { svg, unplaceable } = art(kind, sc, Number(digitsRaw), label || kind.toUpperCase(), sub || '');
if (unplaceable.length) {
  console.error(`SKIP ${kind}: pin(s) not on a top/bottom edge — ${unplaceable.join(', ')}`);
  process.exit(1);
}
fs.writeFileSync(path.join(PARTS_DIR, `${kind}.svg`), svg);
console.log(`wrote parts/${kind}.svg (${digitsRaw} digits, ${sc.w}x${sc.h}, ${sc.terminals.length} pins)`);
