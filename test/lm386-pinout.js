#!/usr/bin/env node
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {execFileSync} = require('node:child_process');

const root = path.join(__dirname, '..');
const jsonPath = path.join(root, 'parts', 'lm386.json');
const svgPath = path.join(root, 'parts', 'lm386.svg');
const part = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
const pinOrder = ['gain1', 'inn', 'inp', 'gnd', 'vout', 'vs', 'bypass', 'gain8'];

assert.equal(part.kind, 'lm386');
assert.deepEqual(part.terminals.map(({name}) => name), pinOrder,
  'terminal array is the TI PDIP-8 physical pin order (SNAS545)');
// Pin 1 bottom-left, counting counter-clockwise seen from above: pins 1-4 on
// the lower row left to right, pins 5-8 on the upper row right to left.
for (let pin = 1; pin <= 8; pin++) {
  const name = pinOrder[pin - 1];
  const lower = pin <= 4;
  assert.deepEqual(part.footprint.leads[name], {
    dRow: lower ? 5 : 0,
    dCol: lower ? pin - 1 : 8 - pin,
  }, `physical pin ${pin} (${name}) occupies its real breadboard column`);
}
assert.equal(part.footprint.straddlesGutter, true);

const svg = fs.readFileSync(svgPath, 'utf8');
assert.match(svg, /LM386 — 8-pin DIP, generated by generate-dip-art\.js from lm386\.json/);
assert.match(svg, />AUDIO POWER AMP</);
for (const name of pinOrder) assert.match(svg, new RegExp(`>${name}<`));

const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'bw-parts-lm386-'));
try {
  fs.mkdirSync(path.join(temp, 'parts'));
  fs.copyFileSync(path.join(root, 'generate-dip-art.js'), path.join(temp, 'generate-dip-art.js'));
  fs.copyFileSync(jsonPath, path.join(temp, 'parts', 'lm386.json'));
  execFileSync(process.execPath, ['generate-dip-art.js', 'lm386'], {cwd: temp, stdio: 'pipe'});
  assert.equal(fs.readFileSync(path.join(temp, 'parts', 'lm386.svg'), 'utf8'), svg,
    'committed LM386 art is exactly generator-owned');
} finally {
  fs.rmSync(temp, {recursive: true, force: true});
}

const ratings = JSON.parse(fs.readFileSync(path.join(root, 'current-ratings.json'), 'utf8'));
assert.equal(ratings.lm386.chip_mA, 0);
assert.equal(ratings.lm386.supply_mA, 8);
console.log('LM386 PDIP-8 pinout, generated art, footprint, and supply budget verified.');
